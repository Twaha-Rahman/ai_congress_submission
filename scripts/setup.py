def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text("utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip("'").strip('"')
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    """Write the deterministic key order, preserving extra operator entries."""

    ordered = dict(ENV_TEMPLATE)
    for key, value in values.items():
        ordered[key] = value
    lines = [
        "# Generated by `make setup`; secrets are local and git-ignored.",
        "# Edit model settings here, never in source code.",
        "",
    ]
    seen_groups = set()
    for key, value in ordered.items():
        group = "model" if "LLM" in key else (
            "token" if key.startswith("DEMO_TOKEN") else (
                "frankfurt" if key.startswith("FRANKFURT") else (
                    "dhaka" if key.startswith("DHAKA") else "general"
                )
            )
        )
        if group not in seen_groups:
            lines.append(f"# --- {group} ---")
            seen_groups.add(group)
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    try:
        path.chmod(0o600)
    except OSError:  # pragma: no cover - platform dependent
        pass


def main() -> int:
    runtime = ROOT / "runtime"
    for region in REGIONS:
        key_dir = runtime / "keys" / region.lower()
        source_dir = runtime / region.lower() / "sources"
        key_dir.mkdir(parents=True, exist_ok=True)
        source_dir.mkdir(parents=True, exist_ok=True)
        # Compose bind-mounts only this office's synthetic replay/cache assets.
        (ROOT / "fixtures" / "cache" / region.lower()).mkdir(
            parents=True, exist_ok=True
        )
    (runtime / "gateway").mkdir(parents=True, exist_ok=True)
    (ROOT / "evidence").mkdir(exist_ok=True)
    (ROOT / "docs" / "openapi").mkdir(parents=True, exist_ok=True)

    env_path = ROOT / ".env"
    values = read_env(env_path)
    if values.get("TENANT_ID") not in (None, "", TENANT_ID):
        print(
            f"refusing to set up tenant {values['TENANT_ID']!r}: this demo only manages "
            f"the {TENANT_ID!r} tenant",
            file=sys.stderr,
        )
        return 1

    # ------------------------------------------------------------ bearer tokens
    created_tokens = []
    for name in TOKEN_ENV_NAMES:
        if not values.get(name):
            values[name] = secrets.token_urlsafe(24)
            created_tokens.append(name)

    # --------------------------------------------------------------- signing keys
    for key, value in values.items():
        if value:
            os.environ.setdefault(key, value)
    keys = []
    for region in REGIONS:
        settings = OfficeSettings.from_env(region, tenant_id=TENANT_ID)
        # Relative paths resolve against the repository, not the caller's cwd.
        key_dir = settings.key_dir if settings.key_dir.is_absolute() else ROOT / settings.key_dir
        signer = Signer.load_or_create(
            key_id=settings.key_id, region=region, key_dir=key_dir
        )
        keys.append(signer.trusted_key())
        try:
            shown = key_dir.relative_to(ROOT)
        except ValueError:
            shown = key_dir
        print(f"signing key  {region:<9} {signer.key_id}  {shown}")

    registry = PinnedKeyRegistry(keys)
    trusted_path = ROOT / "runtime" / "trusted_keys.json"
    registry.write_json_file(trusted_path)
    print(f"trusted keys {trusted_path.relative_to(ROOT)}  ({len(registry.key_ids())} pins)")

    write_env(env_path, values)
    print(f"environment  {env_path.relative_to(ROOT)}  ({len(created_tokens)} new tokens)")

    # Fixtures are generated from their checked-in generator rather than hand-edited.
    if not (ROOT / "fixtures" / "demo_plan.json").exists():
        print("fixtures missing; run: .venv/bin/python scripts/make_fixtures.py", file=sys.stderr)
        return 1

    print("\nsetup complete. Next: make up && make seed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
